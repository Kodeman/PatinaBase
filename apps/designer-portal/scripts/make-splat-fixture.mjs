/**
 * Generates the committed Gaussian-splat fixture used by the SPLAT stage's tests and by
 * its dev `?splatUrl=` override (Rendered Room v2, W2).
 *
 * Output: `public/fixtures/splat/room-fixture.ply` — a 3DGS-convention binary PLY, the
 * interchange format every splat renderer reads (INRIA's original `train.py` layout:
 * position, unused normals, SH DC colour, logit opacity, log scale, wxyz quaternion).
 *
 * DETERMINISTIC BY CONSTRUCTION. The point set comes from a fixed-seed 32-bit LCG, so
 * re-running this script reproduces the committed bytes exactly — the fixture's sha256 in
 * `public/fixtures/splat/README.md` is a real regression signal, not a timestamp.
 *
 *   node scripts/make-splat-fixture.mjs
 */

import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'public',
  'fixtures',
  'splat',
  'room-fixture.ply',
);

/** Gaussians per surface — 6 surfaces × 60 = 360, small enough to commit, dense enough to read as a room. */
const PER_SURFACE = 60;

/** Room extent in metres (a RoomPlan splat is metre-scaled). */
const ROOM = { w: 4, h: 2.5, d: 3 };

/** Spherical-harmonics DC scale — colour = 0.5 + C0·f_dc (the 3DGS convention). */
const SH_C0 = 0.28209479177387814;

/** Fixed-seed LCG (Numerical Recipes constants) — the whole reason the bytes are stable. */
function lcg(seed) {
  let state = seed >>> 0;
  return () => {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    return state / 0x100000000;
  };
}

const rand = lcg(20260818);

const logit = (p) => Math.log(p / (1 - p));
const fromColour = (c) => (c - 0.5) / SH_C0;

/** One surface's worth of gaussians, jittered inside the plane by the seeded stream. */
function surface(plane, colour) {
  const out = [];
  for (let i = 0; i < PER_SURFACE; i += 1) {
    const u = rand();
    const v = rand();
    out.push({
      ...plane(u, v),
      colour,
      // Slight per-gaussian size variation so the cloud doesn't read as a lattice.
      scale: 0.05 + rand() * 0.03,
      opacity: 0.85 + rand() * 0.1,
    });
  }
  return out;
}

const { w, h, d } = ROOM;
const gaussians = [
  // floor / ceiling
  ...surface((u, v) => ({ x: u * w, y: 0, z: v * d }), [0.45, 0.36, 0.28]),
  ...surface((u, v) => ({ x: u * w, y: h, z: v * d }), [0.92, 0.9, 0.86]),
  // four walls
  ...surface((u, v) => ({ x: 0, y: v * h, z: u * d }), [0.86, 0.82, 0.75]),
  ...surface((u, v) => ({ x: w, y: v * h, z: u * d }), [0.86, 0.82, 0.75]),
  ...surface((u, v) => ({ x: u * w, y: v * h, z: 0 }), [0.88, 0.85, 0.79]),
  ...surface((u, v) => ({ x: u * w, y: v * h, z: d }), [0.88, 0.85, 0.79]),
];

const PROPERTIES = [
  'x', 'y', 'z',
  'nx', 'ny', 'nz',
  'f_dc_0', 'f_dc_1', 'f_dc_2',
  'opacity',
  'scale_0', 'scale_1', 'scale_2',
  'rot_0', 'rot_1', 'rot_2', 'rot_3',
];

const header =
  'ply\n' +
  'format binary_little_endian 1.0\n' +
  'comment Patina Room View SPLAT fixture — generated by scripts/make-splat-fixture.mjs\n' +
  `element vertex ${gaussians.length}\n` +
  PROPERTIES.map((p) => `property float ${p}\n`).join('') +
  'end_header\n';

const body = Buffer.alloc(gaussians.length * PROPERTIES.length * 4);
let offset = 0;
const put = (value) => {
  body.writeFloatLE(value, offset);
  offset += 4;
};

for (const g of gaussians) {
  put(g.x); put(g.y); put(g.z);
  put(0); put(0); put(0);                                   // normals: unused by 3DGS, present by convention
  put(fromColour(g.colour[0]));
  put(fromColour(g.colour[1]));
  put(fromColour(g.colour[2]));
  put(logit(g.opacity));                                    // opacity is stored as a logit
  put(Math.log(g.scale)); put(Math.log(g.scale)); put(Math.log(g.scale)); // scale is stored as a log
  put(1); put(0); put(0); put(0);                           // rotation quaternion, wxyz, identity
}

const bytes = Buffer.concat([Buffer.from(header, 'ascii'), body]);
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, bytes);

process.stdout.write(
  `${OUT}\n  ${gaussians.length} gaussians · ${bytes.length} bytes\n` +
    `  sha256 ${createHash('sha256').update(bytes).digest('hex')}\n`,
);
